const CAPTCHA_X_STARTS: [usize; 4] = [5, 14, 23, 32];

/// Decodes a PNG image and returns its width, height, and grayscale luminance values (0..255).
pub fn decode_png_to_luma(png_bytes: &[u8]) -> Option<(usize, usize, Vec<u8>)> {
    let mut decoder = png::Decoder::new(Cursor::new(png_bytes));
    decoder.set_transformations(Transformations::EXPAND);
    let mut reader = decoder.read_info().ok()?;
    let mut buf = vec![0; reader.output_buffer_size()];
    let info = reader.next_frame(&mut buf).ok()?;
    let width = info.width as usize;
    let height = info.height as usize;

    let mut luma = Vec::with_capacity(width * height);
    match info.color_type {
        png::ColorType::Grayscale => {
            if buf.len() < width * height {
                return None;
            }
            luma.extend_from_slice(&buf[..width * height]);
        }
        png::ColorType::GrayscaleAlpha => {
            if buf.len() < width * height * 2 {
                return None;
            }
            for chunk in buf.as_chunks::<2>().0.iter().take(width * height) {
                luma.push(chunk[0]);
            }
        }
        png::ColorType::Rgb => {
            if buf.len() < width * height * 3 {
                return None;
            }
            for chunk in buf.as_chunks::<3>().0.iter().take(width * height) {
                let l = ((chunk[0] as u32 * 299 + chunk[1] as u32 * 587 + chunk[2] as u32 * 114)
                    / 1000) as u8;
                luma.push(l);
            }
        }
        png::ColorType::Rgba => {
            if buf.len() < width * height * 4 {
                return None;
            }
            for chunk in buf.as_chunks::<4>().0.iter().take(width * height) {
                let l = ((chunk[0] as u32 * 299 + chunk[1] as u32 * 587 + chunk[2] as u32 * 114)
                    / 1000) as u8;
                luma.push(l);
            }
        }
        _ => return None,
    }

    Some((width, height, luma))
}

/// Deterministically solves the 4-digit security code generated by PHP GD font 5.
/// Returns the 4-character string on success, or None if matching is ambiguous or image is invalid.
pub fn solve_captcha_png(image_bytes: &[u8]) -> Option<String> {
    let (width, height, luma) = decode_png_to_luma(image_bytes)?;
    if width < 45 || height < 20 {
        return None;
    }

    let mut result = String::with_capacity(4);

    for &x_start in &CAPTCHA_X_STARTS {
        if x_start + 9 > width {
            return None;
        }

        let mut grid = String::with_capacity(100);
        for y in 8..18 {
            if y >= height {
                return None;
            }
            for dx in 0..9 {
                let px = x_start + dx;
                let val = luma[y * width + px];
                if val > 128 {
                    grid.push('1');
                } else {
                    grid.push('0');
                }
            }
            if y < 17 {
                grid.push('\n');
            }
        }

        let mut best_char = '?';
        let mut best_dist = usize::MAX;

        for (ch, tmpl) in GD_FONT5_TEMPLATES {
            let dist = grid
                .chars()
                .zip(tmpl.chars())
                .filter(|(a, b)| a != b && (*a == '0' || *a == '1') && (*b == '0' || *b == '1'))
                .count();
            if dist < best_dist {
                best_dist = dist;
                best_char = ch;
            }
        }

        if best_dist > 6 {
            return None;
        }
        result.push(best_char);
    }

    Some(result)
}

/// HTTP adapter for BioVPN online portal using reqwest.
#[derive(Clone)]
pub struct ReqwestBioVpnClient {
    base_url: String,
    client: reqwest::Client,
    logger: Option<std::sync::Arc<dyn Fn(String) + Send + Sync>>,
}

impl ReqwestBioVpnClient {
    /// Creates a new BioVPN client targeting the specified base URL (defaulting to https://bio4co.com).
    pub fn new(base_url: Option<&str>) -> Result<Self> {
        let base = base_url
            .unwrap_or("https://bio4co.com")
            .trim_end_matches('/');
        let client = reqwest::Client::builder()
            .cookie_store(true)
            .user_agent(
                "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36",
            )
            .timeout(std::time::Duration::from_secs(20))
            .build()
            .context("Failed to build HTTP client")?;

        Ok(Self {
            base_url: base.to_string(),
            client,
            logger: None,
        })
    }

    /// Attaches an asynchronous log callback for streaming real-time sync progress.
    pub fn with_logger<F>(mut self, f: F) -> Self
    where
        F: Fn(String) + Send + Sync + 'static,
    {
        self.logger = Some(std::sync::Arc::new(f));
        self
    }

    fn log(&self, msg: impl Into<String>) {
        if let Some(ref l) = self.logger {
            l(msg.into());
        }
    }

    /// Internal helper to extract the OpenVPN zip download link from dashboard HTML.
    pub fn find_zip_download_url(&self, html: &str) -> Option<String> {
        let mut candidates = Vec::new();

        let bytes = html.as_bytes();
        let mut i = 0;
        while i + 5 <= bytes.len() {
            if bytes[i..i + 5].eq_ignore_ascii_case(b"href=") {
                let mut start = i + 5;
                while start < bytes.len() && (bytes[start] == b' ' || bytes[start] == b'\t') {
                    start += 1;
                }
                if start < bytes.len() {
                    let quote = bytes[start];
                    if quote == b'"' || quote == b'\'' {
                        start += 1;
                        let mut end = start;
                        while end < bytes.len() && bytes[end] != quote {
                            end += 1;
                        }
                        if end < bytes.len() {
                            if let Ok(link) = std::str::from_utf8(&bytes[start..end]) {
                                let link = link.trim();
                                let link_lower = link.to_lowercase();
                                if link_lower.contains(".zip")
                                    && !link_lower.contains("smart-bio")
                                    && !link_lower.contains("app")
                                    && !link_lower.contains("exe")
                                    && !link_lower.contains("2client")
                                    && !link_lower.contains("setup")
                                    && !link_lower.contains("install")
                                    && !link_lower.contains(".pbk")
                                {
                                    candidates.push(link.to_string());
                                }
                            }
                            i = end + 1;
                            continue;
                        }
                    }
                }
            }
            i += 1;
        }

        if candidates.is_empty() {
            return None;
        }

        candidates.sort_by_key(|link| {
            let lower = link.to_lowercase();
            if lower.contains("smarttcp") || lower.contains("smart-tcp") {
                0
            } else if lower.contains("openvpn") {
                1
            } else if lower.contains("tcpx") || lower.contains("tcp") {
                2
            } else if lower.contains("config") {
                3
            } else {
                4
            }
        });

        let best = &candidates[0];
        let full_url = if best.starts_with("http://") || best.starts_with("https://") {
            best.clone()
        } else {
            format!("{}/{}", self.base_url, best.trim_start_matches('/'))
        };

        Some(full_url)
    }
}

impl BioVpnClient for ReqwestBioVpnClient {
    fn fetch_bundle(
        &self,
        username: &str,
        password: &str,
    ) -> impl Future<Output = Result<PortalSyncData>> + Send {
        let client = self.client.clone();
        let base_url = self.base_url.clone();
        let username = username.to_string();
        let password = password.to_string();
        let this = self.clone();

        async move {
            let mut clientarea_url = format!("{}/clientarea/", base_url);
            let mut login_success = false;

            this.log(format!(
                "[SYNC] Connecting to BioVPN portal at {}...",
                base_url
            ));

            for attempt in 1..=3 {
                this.log(format!("[SYNC] Authenticating (attempt {}/3)...", attempt));
                // 1. Initial GET to clientarea to establish session cookies
                let init_res = client.get(&clientarea_url).send().await?;
                if init_res.status() == reqwest::StatusCode::NOT_FOUND {
                    clientarea_url = format!("{}/clientarea", base_url);
                }

                // 2. Fetch CAPTCHA image
                let captcha_url = format!("{}/captcha.php", base_url);
                let cap_res = client.get(&captcha_url).send().await?;
                if !cap_res.status().is_success() {
                    return Err(anyhow!(
                        "Failed to fetch security code verification image from {}",
                        captcha_url
                    ));
                }

                let cap_bytes = cap_res.bytes().await?;
                let captcha_code = solve_captcha_png(&cap_bytes).ok_or_else(|| {
                    anyhow!("Unable to automatically solve portal security code verification")
                })?;
                this.log(format!(
                    "[SYNC] Solved security verification: {}",
                    captcha_code
                ));

                // 3. Submit authentication form
                let params = [
                    ("user", username.as_str()),
                    ("pass", password.as_str()),
                    ("captcha", captcha_code.as_str()),
                    ("Login_From", "1"),
                ];

                let post_res = client.post(&clientarea_url).form(&params).send().await?;
                let post_status = post_res.status();
                let post_text = post_res.text().await.unwrap_or_default();

                if post_text.contains("پنل کاربری") || post_status == reqwest::StatusCode::FOUND
                {
                    login_success = true;
                    break;
                } else if post_text.contains("مشخصات ورود") && post_text.contains("کد امنیتی")
                {
                    this.log("[WARN] Portal login returned invalid credentials or security code mismatch");
                    if attempt == 3 {
                        return Err(anyhow!(
                            "Login failed: Invalid username/password or incorrect security code."
                        ));
                    }
                } else if !post_text.contains("bio-login-form") {
                    login_success = true;
                    break;
                }
            }

            if !login_success {
                return Err(anyhow!("Authentication failed for user '{}'", username));
            }

            this.log("[SYNC] Authentication succeeded. Retrieving user dashboard...");

            // 4. Access clientarea dashboard to find bundle link
            let dash_res = client.get(&clientarea_url).send().await?;
            let dash_text = dash_res.text().await.unwrap_or_default();

            let download_url = this
                .find_zip_download_url(&dash_text)
                .unwrap_or_else(|| format!("{}/dl/BioVPN-SmartTCP.zip", base_url));

            this.log(format!(
                "[SYNC] Downloading configuration bundle ZIP from {}...",
                download_url
            ));

            // 5. Download the zip bundle
            let zip_res = client.get(&download_url).send().await?;
            if !zip_res.status().is_success() {
                return Err(anyhow!(
                    "Failed to download configuration bundle from {} (HTTP {})",
                    download_url,
                    zip_res.status()
                ));
            }

            let zip_bytes = zip_res.bytes().await?;
            this.log(format!(
                "[SYNC] ZIP bundle downloaded ({} bytes).",
                zip_bytes.len()
            ));

            // 6. Download individual OpenVPN configs for table servers sequentially
            let mut individual_ovpns = Vec::new();
            let mut logs = Vec::new();

            if let Ok(parsed) = crate::domain::importer::ProfileImporter::parse_portal_html(
                &dash_text,
                None,
                Some(&base_url),
            ) {
                let servers_with_ovpn: Vec<_> = parsed
                    .servers
                    .into_iter()
                    .filter(|s| s.ovpn_download_url.is_some())
                    .collect();

                let total = servers_with_ovpn.len();
                if total > 0 {
                    this.log(format!(
                        "[SYNC] Downloading {} OpenVPN configs from dashboard table...",
                        total
                    ));
                }

                for (idx, s) in servers_with_ovpn.into_iter().enumerate() {
                    let ovpn_url = s.ovpn_download_url.as_ref().unwrap();
                    this.log(format!(
                        "[SYNC] [{}/{}] Downloading OpenVPN config for '{}'...",
                        idx + 1,
                        total,
                        s.name
                    ));
                    let resp = client
                        .get(ovpn_url)
                        .timeout(std::time::Duration::from_secs(15))
                        .send()
                        .await;

                    match resp {
                        Ok(res) if res.status().is_success() => match res.text().await {
                            Ok(text) if !text.trim().is_empty() => {
                                let filename =
                                    crate::domain::importer::ProfileImporter::derive_ovpn_filename(
                                        ovpn_url,
                                        &s.country_group,
                                        &s.name,
                                    );
                                individual_ovpns.push(crate::ports::biovpn::DownloadedOvpnConfig {
                                    server_name: s.name.clone(),
                                    country_group: s.country_group.clone(),
                                    filename,
                                    content: text,
                                });
                                this.log(format!(
                                    "[SYNC] [{}/{}] Saved OpenVPN config for '{}'",
                                    idx + 1,
                                    total,
                                    s.name
                                ));
                            }
                            Ok(_) => {
                                let warn = format!(
                                    "Warning: Empty OpenVPN config returned for '{}' from {}",
                                    s.name, ovpn_url
                                );
                                this.log(format!("[WARN] {}", warn));
                                logs.push(warn);
                            }
                            Err(e) => {
                                let warn = format!(
                                    "Warning: Failed reading OpenVPN response for '{}': {}",
                                    s.name, e
                                );
                                this.log(format!("[WARN] {}", warn));
                                logs.push(warn);
                            }
                        },
                        Ok(res) => {
                            let warn = format!(
                                "Warning: Failed to download OpenVPN config for '{}' from {} (HTTP {})",
                                s.name,
                                ovpn_url,
                                res.status()
                            );
                            this.log(format!("[WARN] {}", warn));
                            logs.push(warn);
                        }
                        Err(e) => {
                            let warn = format!(
                                "Warning: Error downloading OpenVPN config for '{}' from {}: {}",
                                s.name, ovpn_url, e
                            );
                            this.log(format!("[WARN] {}", warn));
                            logs.push(warn);
                        }
                    }
                }
            }

            Ok(PortalSyncData {
                zip_bytes: zip_bytes.to_vec(),
                dashboard_html: Some(dash_text),
                individual_ovpns,
                logs,
            })
        }
    }

    fn fetch_direct_bundle(&self) -> impl Future<Output = Result<PortalSyncData>> + Send {
        let client = self.client.clone();
        let base_url = self.base_url.clone();
        let this = self.clone();

        async move {
            let download_url = format!("{}/dl/BioVPN-SmartTCP.zip", base_url);
            this.log(format!(
                "[SYNC] Downloading configuration bundle directly from {}...",
                download_url
            ));
            let zip_res = client.get(&download_url).send().await?;
            if !zip_res.status().is_success() {
                return Err(anyhow!(
                    "Failed to download configuration bundle directly from {} (HTTP {})",
                    download_url,
                    zip_res.status()
                ));
            }

            let zip_bytes = zip_res.bytes().await?;
            this.log(format!(
                "[SYNC] Direct configuration bundle downloaded ({} bytes).",
                zip_bytes.len()
            ));
            Ok(PortalSyncData {
                zip_bytes: zip_bytes.to_vec(),
                dashboard_html: None,
                individual_ovpns: Vec::new(),
                logs: Vec::new(),
            })
        }
    }
}

